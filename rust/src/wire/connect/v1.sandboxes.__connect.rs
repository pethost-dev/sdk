/// What runs inside one sandbox: commands, files, the desktop, coding agents, links. Answered by
/// the sandbox's own server at Connection.url, with `Authorization: Bearer <Connection.token>`;
/// Connection.url is the sandbox's server, the same for every sandbox there, so one connection
/// serves them all. Every request names its sandbox; a token for another sandbox is
/// `PERMISSION_DENIED`. Commands run as `user` (with passwordless sudo, when the template's image
/// has sudo: ours do) in /home/user unless a request says otherwise. Paths are absolute, or
/// relative to /home/user.
///
/// Its refusals, beside the header's: INVALID_ARGUMENT = a bad field, named, or a request_id sent
/// again with other fields. FAILED_PRECONDITION = as the RPC says. UNAUTHENTICATED = a token is
/// missing, wrong, expired or revoked (UpdateSandbox.revoke_tokens). `UNAUTHENTICATED`,
/// `PERMISSION_DENIED` (a token of another server, after a move) and `NOT_FOUND` (the server let
/// the sandbox go to another) answer a call that did nothing: connect again and repeat it.
///
/// Bounds: a response holds ~64 KiB at most, but for ReadFile (up to 1 MiB) and ControlDesktop's
/// screenshot; a file of any size moves through CreateLink. A request holds 1 MiB at most (a
/// command with its stdin, a prompt), but WriteFiles's 17 MiB; and a message the sandbox made
/// larger than 1 MiB and the rest of its answer (a screenshot: 17 MiB) is never passed on. A caller
/// has 60 s, and a second more for each 64 KiB, to send its request and to take each message: one
/// slower loses the call. A sandbox serves 64 calls at once, streams, links and SSH channels
/// included, a WriteFiles or a ControlDesktop counting as 16. A message over its bound, or a call
/// past the 64, is RESOURCE_EXHAUSTED without LimitReached: end one, or wait.
///
/// A sandbox keeps the request_ids of what runs in it (RunCommand, PromptAgent) on its disk,
/// unsynced: one that lost its memory (STOPPED) may have lost those of its last seconds too, and a
/// retry of one of them runs again.
///
/// # Implementing handlers
///
/// Implement methods with plain `async fn`; the returned future satisfies
/// the `Send` bound automatically.
///
/// **Unary and server-streaming requests** arrive as
/// [`ServiceRequest<'_, Req>`](::connectrpc::ServiceRequest): a zero-copy
/// view of the request plus its body, valid for the duration of the call.
/// Fields are read directly (`request.name` is a `&str` into the decoded
/// buffer) and the borrow may be held across `.await` points. Anything
/// that must outlive the call — `tokio::spawn`, channels, server state,
/// or data captured by a returned response stream — takes owned data:
/// call `request.to_owned_message()` (or copy the specific fields)
/// first.
///
/// **Client-streaming and bidi requests** arrive as
/// [`InboundStream<Req>`](::connectrpc::InboundStream) — a
/// `ServiceStream` of [`StreamMessage`](::connectrpc::StreamMessage)s.
/// Each item owns its decoded buffer and is `Send + 'static`, so items
/// can be buffered or moved into spawned tasks; read fields zero-copy
/// through the generated accessor methods (`item.name()`) or `.view()`,
/// convert with `.to_owned_message()`, or yield an item back unchanged —
/// `StreamMessage<M>` implements `Encodable<M>`.
///
/// Request types resolved through `extern_path` (e.g. well-known types
/// from another crate) use the same wrappers; the crate that owns the
/// type must be generated with buffa ≥ 0.9.0 and views enabled so the
/// backing `HasMessageView` impl exists.
///
/// The `impl Encodable<Out>` return bound accepts the owned `Out`, the
/// generated `OutView<'_>` / `OwnedOutView`,
/// [`MaybeBorrowed`](::connectrpc::MaybeBorrowed), or
/// [`PreEncoded`](::connectrpc::PreEncoded) for handlers that encode a
/// non-`'static` view internally and pass the bytes across the handler
/// boundary. View bodies are not emitted for output types mapped via
/// `extern_path` (the impl would be an orphan); return owned for
/// WKT/extern outputs.
///
/// Server-streaming and bidi-streaming methods return
/// `ServiceStream<impl Encodable<Out> + Send + use<Self>>`. The
